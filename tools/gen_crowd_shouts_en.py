"""
English crowd shouts, voiced with ElevenLabs. The English twin of gen_crowd_shouts.py.
Reads the phrases from tools/shouts_en.txt ("MOMENT | phrase", one per line; the six battle moments are used,
SOLO_* lines are ignored) and writes
  - assets/rapbattle/sounds/shout_en/<moment>_<n>.ogg
  - sounds.json entries "shout_en.<moment>.<n>"
  - battle/ShoutsEn.java with the same phrases, so the bubble over the fan shows exactly what is heard.
Needs the ElevenLabs key in the file given as the first argument (never stored in the project).

Run: python tools/gen_crowd_shouts_en.py <path-to-key-file>
"""
import json
import os
import subprocess
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', 'src', 'main')
SND = os.path.join(ROOT, 'resources', 'assets', 'rapbattle', 'sounds', 'shout_en')
SOUNDS_JSON = os.path.join(ROOT, 'resources', 'assets', 'rapbattle', 'sounds.json')
JAVA = os.path.join(ROOT, 'java', 'dev', 'rapbattle', 'battle', 'ShoutsEn.java')
MOMENTS = ['START', 'PLAYER_HIT', 'MOB_PUNCH', 'PLAYER_MISS', 'WIN_PLAYERS', 'WIN_MOB']


def phrases():
    out = {m: [] for m in MOMENTS}
    for line in open(os.path.join(HERE, 'shouts_en.txt'), encoding='utf-8'):
        if '|' not in line:
            continue
        moment, text = (x.strip() for x in line.split('|', 1))
        if moment in out and text:
            out[moment].append(text)
    return out


def get(key, path):
    req = urllib.request.Request('https://api.elevenlabs.io' + path, headers={'xi-api-key': key})
    return json.load(urllib.request.urlopen(req, timeout=60))


def english_voices(key):
    """Six different English voices from the account (American/British accents), men first, then women."""
    voices = get(key, '/v1/voices')['voices']
    def ok(v):
        lab = {k: str(x).lower() for k, x in (v.get('labels') or {}).items()}
        return lab.get('accent', '') in ('american', 'british', 'australian', 'irish') or lab.get('language', '') == 'en'
    eng = [v for v in voices if ok(v)]
    men = [v for v in eng if (v.get('labels') or {}).get('gender') == 'male']
    women = [v for v in eng if (v.get('labels') or {}).get('gender') == 'female']
    picked = (men[:4] + women[:2]) or eng[:6]
    if len(picked) < 6:
        picked += [v for v in eng if v not in picked][:6 - len(picked)]
    print('voices:', ', '.join(v['name'] for v in picked))
    return [v['voice_id'] for v in picked]


def tts(key, voice, text):
    body = json.dumps({
        'text': text,
        'model_id': 'eleven_multilingual_v2',
        'voice_settings': {'stability': 0.25, 'similarity_boost': 0.75, 'style': 0.7, 'use_speaker_boost': True},
    }).encode()
    req = urllib.request.Request(f'https://api.elevenlabs.io/v1/text-to-speech/{voice}?output_format=mp3_44100_128', data=body,
                                 headers={'xi-api-key': key, 'Content-Type': 'application/json'}, method='POST')
    return urllib.request.urlopen(req, timeout=120).read()


def main():
    key = open(sys.argv[1]).read().strip()
    lines = phrases()
    voices = english_voices(key)
    os.makedirs(SND, exist_ok=True)
    tmp = os.path.join(SND, '_tmp.mp3')
    v = 0
    for moment in MOMENTS:
        for i, text in enumerate(lines[moment], 1):
            ogg = os.path.join(SND, f'{moment.lower()}_{i}.ogg')
            if not os.path.exists(ogg):
                open(tmp, 'wb').write(tts(key, voices[v % len(voices)], text))
                subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', tmp, '-af',
                                'highpass=f=120,aecho=0.8:0.5:60|110:0.25|0.15,volume=-1dB',
                                '-ac', '1', '-ar', '44100', '-c:a', 'libvorbis', '-q:a', '4', ogg], check=True)
                print(moment, i, text)
            v += 1
    if os.path.exists(tmp):
        os.remove(tmp)

    sounds = json.load(open(SOUNDS_JSON, encoding='utf-8'))
    for moment in MOMENTS:
        for i in range(1, len(lines[moment]) + 1):
            sounds[f'shout_en.{moment.lower()}.{i}'] = {'sounds': [{'name': f'rapbattle:shout_en/{moment.lower()}_{i}', 'attenuation_distance': 32}]}
    json.dump(sounds, open(SOUNDS_JSON, 'w', encoding='utf-8'), indent=2, ensure_ascii=False)

    java = ['package dev.rapbattle.battle;', '', '// Generated by tools/gen_crowd_shouts_en.py: the text matches the voiced audio. Do not edit by hand.', '',
            'import java.util.List;', 'import java.util.Map;', '',
            '/** English phrases a fan yells from the crowd, per moment; index i plays sound shout_en.<moment>.<i+1>. */',
            'public final class ShoutsEn {', '\tprivate ShoutsEn() {}', '',
            '\tpublic static final Map<Crowd.Moment, List<String>> LINES = Map.of(']
    entries = []
    for moment in MOMENTS:
        quoted = ', '.join('"' + l.replace('\\', '\\\\').replace('"', '\\"') + '"' for l in lines[moment])
        entries.append(f'\t\tCrowd.Moment.{moment}, List.of({quoted})')
    java.append(',\n'.join(entries) + ');')
    java.append('}')
    open(JAVA, 'w', encoding='utf-8').write('\n'.join(java) + '\n')
    print('done')


main()
