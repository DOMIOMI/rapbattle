"""
Crowd shouts: full phrases yelled by someone in the crowd, voiced with ElevenLabs (Russian voices).
One source of truth for the text and the audio: this script writes
  - assets/rapbattle/sounds/shout/<moment>_<n>.ogg   (the voice, with a little hall reverb)
  - sounds.json entries "shout.<moment>.<n>"
  - battle/Shouts.java with the same phrases, so the bubble over the fan shows exactly what is heard.
Needs the ElevenLabs key in the file given as the first argument (never stored in the project).

Run: python tools/gen_crowd_shouts.py <path-to-key-file>
"""
import json
import os
import subprocess
import sys
import urllib.request

ROOT = os.path.join(os.path.dirname(__file__), '..', 'src', 'main')
SND = os.path.join(ROOT, 'resources', 'assets', 'rapbattle', 'sounds', 'shout')
SOUNDS_JSON = os.path.join(ROOT, 'resources', 'assets', 'rapbattle', 'sounds.json')
JAVA = os.path.join(ROOT, 'java', 'dev', 'rapbattle', 'battle', 'Shouts.java')

VOICES = ['ouyTiWqmHA5WI5bbX7zj', 'XuEV9VY3VUASYgJVNBh0', 'USJ5Rjf2LwNEcibI3sN4', 'QSM8BzHrVEW9vi9xYs4U',
          'TUQNWEvVPBLzMBSVDPUA', 'wUndevsXFk0ArF7vJ61U']

PHRASES = {
    'START': ['Давай, жги!', 'Погнали уже!', 'Покажи ему, кто тут главный!', 'Ну-ка, ну-ка, посмотрим!', 'Разнеси его!',
              'Микрофон в руки и вперёд!'],
    'PLAYER_HIT': ['Вот это да!', 'Красава!', 'Жёстко! Ещё давай!', 'Хорош, хорош!', 'В точку!', 'Он его разматывает!'],
    'MOB_PUNCH': ['Ооо, это больно!', 'Он тебя уделал!', 'Жёсткий панч!', 'Отвечай давай!', 'Да ладно?!', 'Это было грязно!'],
    'PLAYER_MISS': ['Ну ты чего?!', 'Мимо!', 'Слабо!', 'Скажи хоть что-нибудь!', 'Уноси его!', 'Где рифма, брат?!'],
    'WIN_PLAYERS': ['Красавчик!', 'Вот это баттл!', 'Уважение!', 'Легенда!', 'Разнёс, разнёс!', 'Он сделал это!'],
    'WIN_MOB': ['Иди тренируйся!', 'Позорище!', 'Он тебя похоронил!', 'Сливайся!', 'Ну и где твой флоу?', 'Даже курица бы смогла!'],
}


def tts(key, voice, text):
    body = json.dumps({
        'text': text,
        'model_id': 'eleven_multilingual_v2',
        'voice_settings': {'stability': 0.25, 'similarity_boost': 0.75, 'style': 0.7, 'use_speaker_boost': True},
    }).encode()
    req = urllib.request.Request(f'https://api.elevenlabs.io/v1/text-to-speech/{voice}?output_format=mp3_44100_128', data=body,
                                 headers={'xi-api-key': key, 'Content-Type': 'application/json'}, method='POST')
    return urllib.request.urlopen(req, timeout=120).read()


def main():
    key = open(sys.argv[1]).read().strip()
    os.makedirs(SND, exist_ok=True)
    tmp = os.path.join(SND, '_tmp.mp3')
    v = 0
    for moment, lines in PHRASES.items():
        for i, text in enumerate(lines, 1):
            ogg = os.path.join(SND, f'{moment.lower()}_{i}.ogg')
            if not os.path.exists(ogg):
                open(tmp, 'wb').write(tts(key, VOICES[v % len(VOICES)], text))
                # A touch of hall: short echo, a bit of high-pass, mono for positional playback.
                subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', tmp, '-af',
                                'highpass=f=120,aecho=0.8:0.5:60|110:0.25|0.15,volume=-1dB',
                                '-ac', '1', '-ar', '44100', '-c:a', 'libvorbis', '-q:a', '4', ogg], check=True)
                print(moment, i, text)
            v += 1
    if os.path.exists(tmp):
        os.remove(tmp)

    sounds = json.load(open(SOUNDS_JSON, encoding='utf-8'))
    for moment, lines in PHRASES.items():
        for i in range(1, len(lines) + 1):
            sounds[f'shout.{moment.lower()}.{i}'] = {'sounds': [{'name': f'rapbattle:shout/{moment.lower()}_{i}', 'attenuation_distance': 32}]}
    json.dump(sounds, open(SOUNDS_JSON, 'w', encoding='utf-8'), indent=2)

    java = ['package dev.rapbattle.battle;', '', '// Generated by tools/gen_crowd_shouts.py: the text matches the voiced audio. Do not edit by hand.', '',
            'import java.util.List;', 'import java.util.Map;', '',
            '/** Phrases a fan yells from the crowd, per moment; index i plays sound shout.<moment>.<i+1>. */',
            'public final class Shouts {', '\tprivate Shouts() {}', '',
            '\tpublic static final Map<Crowd.Moment, List<String>> LINES = Map.of(']
    entries = []
    for moment, lines in PHRASES.items():
        quoted = ', '.join('"' + l.replace('"', '\\"') + '"' for l in lines)
        entries.append(f'\t\tCrowd.Moment.{moment}, List.of({quoted})')
    java.append(',\n'.join(entries) + ');')
    java.append('}')
    open(JAVA, 'w', encoding='utf-8').write('\n'.join(java) + '\n')
    print('done')


main()
